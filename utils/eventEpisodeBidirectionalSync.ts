import {
  deleteEpisode,
  getEpisodesByEventId,
  getEvent,
  getMyself,
  updateEpisode,
  type EpisodeInput,
} from '../db';
import type { Episode } from '../types';
import { formatDateKey, getLocalDateKeysForEvent, parseDateKey } from './eventHelpers';
import { scheduleOwnedEpisodeDelete, scheduleOwnedEpisodeSync } from '@/lib/ownedEpisodeSync';
import { episodeDetailHrefMatch } from '@/utils/detailRouteMemory';
import { forgetDetailFromTabs } from '@/utils/tabNavigation';

let isSyncingEventEpisode = false;

export const isEventEpisodeSyncInProgress = (): boolean => isSyncingEventEpisode;

const buildEpisodeInputFromEpisode = (
  episode: Episode,
  overrides: Partial<Pick<EpisodeInput, 'date' | 'eventId' | 'tag' | 'locationTag'>>
): EpisodeInput => ({
  title: episode.title,
  date: overrides.date ?? episode.date,
  time: episode.time ?? null,
    description: episode.description,
    privateMemo: episode.privateMemo ?? '',
    visibilityMode: episode.visibilityMode,
  participantEntries: episode.participantEntries,
  visibilityEntries: episode.visibilityEntries,
  eventId: overrides.eventId !== undefined ? overrides.eventId : episode.eventId,
  tag: overrides.tag ?? episode.tag ?? null,
  locationTag: overrides.locationTag ?? episode.locationTag ?? null,
  isAutoGenerated: episode.isAutoGenerated,
  pendingReview: episode.pendingReview,
  pendingReviewDismissed: episode.pendingReviewDismissed,
});

/**
 * 予定の期間が変わったとき、範囲外になったエピソード日付だけ残せる日へクランプする。
 * 予定日に含まれない過去の日付を、未来の開始日へは動かさず、紐づけを解除する。
 * タイトル・タグ・本文・参加者は同期しない（フォルダモデル）。
 */
export const clampLinkedEpisodeDatesToEvent = (eventId: string): void => {
  if (isSyncingEventEpisode) {
    return;
  }

  const normalizedEventId = eventId.trim();
  if (!normalizedEventId) {
    return;
  }

  const event = getEvent(normalizedEventId);
  if (!event) {
    return;
  }

  const todayKey = formatDateKey(new Date());
  const eventDateKeys = getLocalDateKeysForEvent(event);
  const fallbackDate = eventDateKeys.find((key) => key <= todayKey) ?? null;
  const episodes = getEpisodesByEventId(normalizedEventId);

  isSyncingEventEpisode = true;
  try {
    episodes.forEach((episode) => {
      const ownerId = episode.authorFriendId.trim() || getMyself() || '';
      if (!ownerId) {
        return;
      }
      if (eventDateKeys.includes(episode.date)) {
        return;
      }
      if (!fallbackDate) {
        updateEpisode(
          ownerId,
          episode.id,
          buildEpisodeInputFromEpisode(episode, { eventId: null })
        );
        scheduleOwnedEpisodeSync(episode.id);
        return;
      }
      updateEpisode(
        ownerId,
        episode.id,
        buildEpisodeInputFromEpisode(episode, { date: fallbackDate })
      );
      scheduleOwnedEpisodeSync(episode.id);
    });
  } finally {
    isSyncingEventEpisode = false;
  }
};

/** @deprecated 互換用。clampLinkedEpisodeDatesToEvent と同じ */
export const syncLinkedEpisodesFromEvent = clampLinkedEpisodeDatesToEvent;

/** エピソード保存時の予定側への書き戻しは行わない（フォルダモデル） */
export const syncLinkedEventFromEpisode = (
  _episode: Episode,
  _authorFriendId: string
): void => {
  // no-op
};

/** Keep episode dates; clear eventId on all episodes linked to this event. */
export const unlinkEpisodesFromEvent = (eventId: string): void => {
  const normalizedEventId = eventId.trim();
  if (!normalizedEventId) {
    return;
  }
  const episodes = getEpisodesByEventId(normalizedEventId);
  isSyncingEventEpisode = true;
  try {
    episodes.forEach((episode) => {
      const ownerId = episode.authorFriendId.trim() || getMyself() || '';
      if (!ownerId) {
        return;
      }
      updateEpisode(ownerId, episode.id, buildEpisodeInputFromEpisode(episode, { eventId: null }));
      scheduleOwnedEpisodeSync(episode.id);
    });
  } finally {
    isSyncingEventEpisode = false;
  }
};

/** Delete all episodes linked to this event. */
export const deleteEpisodesLinkedToEvent = (eventId: string): void => {
  const normalizedEventId = eventId.trim();
  if (!normalizedEventId) {
    return;
  }
  const episodes = getEpisodesByEventId(normalizedEventId);
  episodes.forEach((episode) => {
    const ownerId = episode.authorFriendId.trim() || getMyself() || '';
    if (!ownerId) {
      return;
    }
    deleteEpisode(ownerId, episode.id);
    forgetDetailFromTabs(episodeDetailHrefMatch(episode.id));
    scheduleOwnedEpisodeDelete(episode.id);
  });
};

/**
 * Episode date picker bounds for a linked event.
 * Includes the event's future days so an episode can be registered before it happens.
 */
export const getLinkedEventDateBounds = (
  eventId: string | null | undefined
): { minimumDate: Date; maximumDate: Date } | null => {
  const normalizedEventId = eventId?.trim();
  if (!normalizedEventId) {
    return null;
  }
  const event = getEvent(normalizedEventId);
  if (!event) {
    return null;
  }
  const dateKeys = getLocalDateKeysForEvent(event);
  if (dateKeys.length === 0) {
    return null;
  }
  return {
    minimumDate: parseDateKey(dateKeys[0]),
    maximumDate: parseDateKey(dateKeys[dateKeys.length - 1]),
  };
};
